const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');
const [id, cwd, exe, ...args] = process.argv.slice(2);
if (!id || !cwd || !exe) throw Error('id cwd executable arguments required');
const prefix = path.join(__dirname, id);
if (fs.existsSync(prefix + '.command.json')) throw Error('EVIDENCE_DIRECTORY_COLLISION');
const record = { run_id: 'CODEX-SF-20261025-VERIFIER-CONFORMANCE-A01', id, cwd, exe, args, started_utc: new Date().toISOString(), expected_writes: 'Declared repair files/evidence; test fixtures; deployment only for explicitly named installer commands' };
fs.writeFileSync(prefix + '.command.json', JSON.stringify(record, null, 2) + '\n');
fs.appendFileSync(path.join(__dirname, 'journal.jsonl'), JSON.stringify({ event: 'command_started', ...record }) + '\n');
const result = cp.spawnSync(exe, args, { cwd, encoding: 'utf8', maxBuffer: 128 * 1024 * 1024, windowsHide: true });
fs.writeFileSync(prefix + '.stdout.txt', result.stdout || '');
fs.writeFileSync(prefix + '.stderr.txt', result.stderr || '');
const finished = { ...record, finished_utc: new Date().toISOString(), inner_exit_code: typeof result.status === 'number' ? result.status : -1, signal: result.signal, error: result.error?.message };
fs.writeFileSync(prefix + '.result.json', JSON.stringify(finished, null, 2) + '\n');
fs.appendFileSync(path.join(__dirname, 'journal.jsonl'), JSON.stringify({ event: 'command_finished', ...finished }) + '\n');
console.log((result.stdout || '').slice(-3500));
console.error((result.stderr || '').slice(-1800));
console.log(JSON.stringify(finished));
process.exit(typeof result.status === 'number' ? result.status : 1);
